GRID_TAIL_TO_WUXING: Dict[int, str] = {
    1: "木", 2: "木",
    3: "火", 4: "火",
    5: "土", 6: "土",
    7: "金", 8: "金",
    9: "水", 0: "水",
}


def get_character_stroke(char: str) -> int:
    """查询单个汉字的标准简体笔画；非汉字返回 0，未收录生僻汉字返回中性估计值 10。"""
    if not char:
        return 0
    if char in STROKE_DICT:
        return STROKE_DICT[char]
    if not _CJK_CHAR_RE.fullmatch(char):
        return 0
    return 10


def split_chinese_name(name: str) -> Tuple[str, str]:
    """拆分中文姓名为 (姓, 名)，支持常见复姓。"""
    clean_name = "".join(_CJK_CHAR_RE.findall(name.strip()))
    if len(clean_name) >= 2 and clean_name[:2] in COMPOUND_SURNAMES:
        return clean_name[:2], clean_name[2:]
    if len(clean_name) >= 1:
        return clean_name[:1], clean_name[1:]
    return "", ""


def compute_grid_wuxing(value: int) -> str:
    """将格数尾数映射为五行。"""
    return GRID_TAIL_TO_WUXING[value % 10]


def compute_grid_fortune(value: int) -> Tuple[str, str]:
    """查询 81 数理吉凶。"""
    v_81 = (value - 1) % 81 + 1 if value > 0 else 1
    return FORTUNE_81.get(v_81, ("平", "数理平平，勤勉自立"))


def analyze_name_numerology(name: str) -> Dict[str, Any]:
    """
    计算中文姓名五格剖象、81 数理与个人精简吉数：
    - 统一使用标准现代简体笔画，标注未收录生僻字；
    - 非汉字（如纯英文/数字）不再用 Unicode 伪笔画强算吉凶；
    - 单字名不强行给外格 1(大吉)，并收紧吉数输出避免全盘稀释。
    """
    raw_name = (name or "").strip()
    if not raw_name:
        return {}

    cjk_chars = _CJK_CHAR_RE.findall(raw_name)
    if not cjk_chars:
        return {
            "user_name": raw_name,
            "is_chinese_name": False,
            "stroke_standard": "现代标准简体笔画",
            "surname": "",
            "given_name": "",
            "character_strokes": {},
            "unmapped_chars": [],
            "primary_element": "",
            "name_lucky_numbers": [],
            "summary": f"【{raw_name}】非中文汉字姓名，不套用汉字五格剖象数理。",
        }

    clean_name = "".join(cjk_chars)
    surname, given_name = split_chinese_name(clean_name)
    s_strokes = [get_character_stroke(c) for c in surname]
    g_strokes = [get_character_stroke(c) for c in given_name]
    unmapped_chars = [c for c in clean_name if c not in STROKE_DICT]

    has_given = len(given_name) > 0
    if len(surname) == 1:
        s1 = s_strokes[0]
        tian_ge = s1 + 1
        if len(given_name) == 1:
            g1 = g_strokes[0]
            ren_ge = s1 + g1
            di_ge = g1 + 1
            zong_ge = s1 + g1
            wai_ge = 2
        elif len(given_name) >= 2:
            g1 = g_strokes[0]
            g2 = g_strokes[1]
            g_rest = sum(g_strokes[2:])
            ren_ge = s1 + g1
            di_ge = g1 + g2 + g_rest
            zong_ge = s1 + di_ge
            wai_ge = max(2, zong_ge - ren_ge + 1)
        else:
            ren_ge = s1
            di_ge = 1
            zong_ge = s1
            wai_ge = 1
    else:
        s1, s2 = s_strokes[0], s_strokes[1]
        tian_ge = s1 + s2
        if len(given_name) == 1:
            g1 = g_strokes[0]
            ren_ge = s2 + g1
            di_ge = g1 + 1
            zong_ge = s1 + s2 + g1
            wai_ge = s1 + 1
        elif len(given_name) >= 2:
            g1 = g_strokes[0]
            g2 = g_strokes[1]
            g_rest = sum(g_strokes[2:])
            ren_ge = s2 + g1
            di_ge = g1 + g2 + g_rest
            zong_ge = s1 + s2 + di_ge
            wai_ge = max(2, zong_ge - ren_ge)
        else:
            ren_ge = s2
            di_ge = 1
            zong_ge = s1 + s2
            wai_ge = s1

    def make_grid_info(val: int, incomplete: bool = False) -> Dict[str, Any]:
        if incomplete:
            return {
                "value": max(1, val),
                "element": compute_grid_wuxing(max(1, val)),
                "fortune": "平",
                "description": "仅输入单姓（未填名），按假添一留存占位，补全名字后可推演完整五格",
            }
        fortune, desc = compute_grid_fortune(val)
        return {
            "value": val,
            "element": compute_grid_wuxing(val),
            "fortune": fortune,
            "description": desc,
        }

    tian_info = make_grid_info(tian_ge)
    ren_info = make_grid_info(ren_ge)
    di_info = make_grid_info(di_ge, incomplete=not has_given)
    wai_info = make_grid_info(wai_ge, incomplete=not has_given)
    zong_info = make_grid_info(zong_ge)

    # 精选高区分度个人吉数（限制在最多 4 个核心数字，避免 66%+ 全盘稀释）
    lucky_ordered: List[int] = []

    def _add_lucky(num: int) -> None:
        if 1 <= num <= 35 and num not in lucky_ordered:
            lucky_ordered.append(num)

    # 1. 人格与总格核心数（优先直接吉格数，再取尾数）
    for g_val, g_info in [(ren_ge, ren_info), (zong_ge, zong_info), (di_ge, di_info)]:
        if "吉" in g_info["fortune"] and 1 <= g_val <= 35:
            _add_lucky(g_val)
    _add_lucky(ren_ge % 10 or 10)
    _add_lucky(zong_ge % 10 or 10)

    # 2. 若仍不足 3 个，补入人格五行核心河图生数
    ren_elem = ren_info["element"]
    hetu_tails = {
        "木": [3, 8],
        "火": [2, 7],
        "土": [5, 10],
        "金": [4, 9],
        "水": [1, 6],
    }.get(ren_elem, [1, 6])
    for ht in hetu_tails:
        if len(lucky_ordered) < 4:
            _add_lucky(ht)

    name_lucky_numbers = sorted(lucky_ordered[:4])
    character_strokes = {c: get_character_stroke(c) for c in clean_name}

    note = f"（其中 {'/'.join(unmapped_chars)} 为非常用字按中性笔画估算）" if unmapped_chars else ""
    summary = (
        f"缘主【{clean_name}】五格剖象（标准简体笔画）：人格{ren_ge}({ren_info['fortune']})属{ren_info['element']}，"
        f"总格{zong_ge}({zong_info['fortune']})属{zong_info['element']}。"
        f"核心共振数：{', '.join(str(n) for n in name_lucky_numbers)}。{note}"
    )

    return {
        "user_name": clean_name,
        "is_chinese_name": True,
        "stroke_standard": "现代标准简体笔画",
        "surname": surname,
        "given_name": given_name,
        "character_strokes": character_strokes,
        "unmapped_chars": unmapped_chars,
        "tian_ge": tian_info,
        "ren_ge": ren_info,
        "di_ge": di_info,
        "wai_ge": wai_info,
        "zong_ge": zong_info,
        "primary_element": ren_info["element"],
        "name_lucky_numbers": name_lucky_numbers,
        "summary": summary,
    }
